"""Faster R-CNN data, model, training, and COCO evaluation helpers.

The module consumes the COCO JSON files generated by ``preprocess_visdrone.py``.
VisDrone categories remain 1..10 because Torchvision reserves label 0 for the
background class.
"""

from __future__ import annotations

import contextlib
import json
import time
from collections import defaultdict
from pathlib import Path
from typing import Any, Callable, Optional, Sequence

import numpy as np
from PIL import Image


